export type TranslationKey = keyof typeof messages['zh-CN']

export function translate(locale: AppLocale, key: TranslationKey): string {
  return messages[locale][key]
}

const permissionKeys: Record<PermissionMode, TranslationKey> = {
  acceptEdits: 'permissionAcceptEdits',
  plan: 'permissionPlan',
  dontAsk: 'permissionDontAsk',
  bypassPermissions: 'permissionBypass',
}

const scopeKeys: Record<SkillScope, TranslationKey> = {
  project: 'scopeProject',
  user: 'scopeUser',
  plugin: 'scopePlugin',
}

const slashCommandDescriptionKeys: Record<DesktopSlashCommandName, TranslationKey> = {
  help: 'slashHelpDescription',
  mcp: 'slashMcpDescription',
  plugin: 'slashPluginDescription',
  memory: 'slashMemoryDescription',
  skills: 'slashSkillsDescription',
  doctor: 'slashDoctorDescription',
  agents: 'slashAgentsDescription',
  status: 'slashStatusDescription',
  compact: 'slashCompactDescription',
  context: 'slashContextDescription',
  permissions: 'slashPermissionsDescription',
  model: 'slashModelDescription',
  config: 'slashConfigDescription',
}

export function permissionLabel(locale: AppLocale, mode: PermissionMode): string {
  return translate(locale, permissionKeys[mode])
}

export function skillScopeLabel(locale: AppLocale, scope: SkillScope): string {
  return translate(locale, scopeKeys[scope])
}

export function slashCommandDescription(locale: AppLocale, command: DesktopSlashCommandName): string {
  return translate(locale, slashCommandDescriptionKeys[command])
}

export function useTranslation() {
  const locale = useAppStore((state) => state.locale)
  return {
    locale,
    t: (key: TranslationKey) => translate(locale, key),
  }
}
